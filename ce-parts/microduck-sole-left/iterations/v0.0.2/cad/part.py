MATERIAL = "TPU"    # SPEC.md: soles + jaw_soft + soft_mouth_top print in TPU (mint #89dad3)


def _rounded_rect(x0, x1, y0, y1, r_front, r_back, n=10):
    """(x, y) polygon, CCW, back corners (y1 side) r_back, front r_front."""
    pts = []
    corners = [
        ((x1 - r_back, y1 - r_back), 0, r_back),
        ((x0 + r_back, y1 - r_back), 90, r_back),
        ((x0 + r_front, y0 + r_front), 180, r_front),
        ((x1 - r_front, y0 + r_front), 270, r_front),
    ]
    for (cx, cy), a0, r in corners:
        for i in range(n + 1):
            a = math.radians(a0 + 90.0 * i / n)
            pts.append((cx + r * math.cos(a), cy + r * math.sin(a)))
    return pts


def _hand_xy(pts):
    """Mirror an (x, y) polygon about x=0 for the right sole, keeping winding."""
    if HAND > 0:
        return pts
    return [(-x, y) for x, y in reversed(pts)]


def _floor_sections(lift):
    """The below-floor cut as loft sections along x: [(pts(y,z), h)].
    lift=0 is the measured outer floor; lift=FLOOR_T the cavity floor."""
    sections = []
    xs = FLOOR_XS if HAND > 0 else [-x for x in reversed(FLOOR_XS)]
    rows = FLOOR_ZB if HAND > 0 else list(reversed(FLOOR_ZB))
    for x, row in zip(xs, rows):
        pts = [(y, z + lift) for y, z in zip(FLOOR_YS, row)]
        pts += [(FLOOR_YS[-1] + 0.5, Z_LOW - 2), (FLOOR_YS[0] - 0.5, Z_LOW - 2)]
        sections.append((pts, x))
    return sections


def build(doc, params=None):
    from cecad.core import Part
    if params:
        raise ValueError("microduck-sole-left takes no build parameters (got %s)" % sorted(params))
    name = "microduck-sole-left" if HAND > 0 else "microduck-sole-right"
    p = Part(name, material=MATERIAL)

    # outer skin: loft of rounded rects through the measured wall sections
    sections = []
    for z, xh, xt in LOFT_XS:
        pts = _hand_xy(_rounded_rect(xh, xt, Y0, Y1, R_FRONT, R_BACK))
        sections.append((pts, z))
    p.loft(sections, axis="z", smooth=False, ruled=True)

    # the measured floor: cut everything below the z_bottom(x,y) table
    p.loft(_floor_sections(0.0), axis="x", smooth=False, ruled=True, op="cut")

    # cavity: vertical-walled socket, floor = outer floor + 2.0 (measured)
    cav = Part("cavity", material=MATERIAL)
    plan = _hand_xy(_rounded_rect(CAV_X0, CAV_X1, CAV_Y0, CAV_Y1, R_CAV_FRONT, R_CAV_BACK))
    cav.prism(plan, Z_RIM - Z_LOW + 2.0, at=(0, 0, Z_LOW), axis="z")
    cav.loft(_floor_sections(FLOOR_T), axis="x", smooth=False, ruled=True, op="cut")
    p.merge(cav, "cut")

    return p
