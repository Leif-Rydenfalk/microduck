#!/usr/bin/env python3
"""Materialize verify.py with input digests: triad-test caches script bytes only."""
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
ASM = ROOT/'ce-assemblies/microduck/current'


def generate():
    inputs = [ASM/(n+'.json') for n in ('placements','joints','bom')]
    inputs += [ASM/'evidence/thread_identity.py']
    joints = json.loads((ASM/'joints.json').read_text())['record']['rows']
    for ref in sorted({j['b']['ref'] for j in joints if j.get('owned_by')=='tools/place_fasteners.py'}):
        inputs.append(ROOT/'ce-parts'/ref.split(':')[1]/'current/cad/interfaces.json')
    hashes = {str(p.relative_to(ROOT)): hashlib.sha256(p.read_bytes()).hexdigest() for p in inputs}
    text = '''# GENERATED by tools/gen_fastener_verify.py; rerun after changing evidence inputs.
"""TRIAD marked entry point; original fastener identity and endpoint evidence."""
import hashlib
import json
import sys
from pathlib import Path

INPUT_SHA256 = ''' + repr(hashes) + '''
try:
    root = Path(__file__).resolve().parents[5]
    stale = [name for name, sha in INPUT_SHA256.items() if hashlib.sha256((root/name).read_bytes()).hexdigest() != sha]
    if stale:
        result = {'verdict': 'CANNOT DETERMINE', 'why': 'Evidence inputs changed; regenerate tools/gen_fastener_verify.py', 'stale': stale}
    else:
        assembly = root/'ce-assemblies/microduck/current'
        sys.path.insert(0, str(assembly/'evidence'))
        from thread_identity import verify
        result = verify(*(json.loads((assembly/(name+'.json')).read_text()) for name in ('placements','joints','bom')))
except BaseException as exc:
    result = {'verdict': 'CANNOT DETERMINE', 'why': '%s: %s' % (type(exc).__name__, exc)}
result.update({'$verify': 1, 'slug': 'microduck', 'input_sha256': INPUT_SHA256})
print(json.dumps(result), flush=True)
raise SystemExit({'PASS': 0, 'FAIL': 1, 'CANNOT DETERMINE': 2}[result['verdict']])
'''
    (ASM/'evidence/verify.py').write_text(text)
    return hashes


if __name__ == '__main__':
    print(json.dumps(generate(), indent=2))
